/* Runs the Karma suite once with coverage over every app source file, not only the files some spec
   imports. It writes a temporary spec that imports each file under src/app (so an untested file is
   reported at 0% instead of missing), runs ng test, then deletes that spec.
   Extra arguments are passed to ng test, e.g. `npm run test:coverage -- --browsers=ChromeHeadless`. */
import { readdirSync, writeFileSync, rmSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { spawnSync } from 'node:child_process';

const root = join(import.meta.dirname, '..');
const appDir = join(root, 'src', 'app');
const tempSpec = join(root, 'src', 'coverage-all-files.spec.ts');

/* test-only helpers are excluded from coverage in angular.json (codeCoverageExclude), so skip them here too */
const isSource = f => f.endsWith('.ts') && !f.endsWith('.spec.ts') && !f.endsWith('.d.ts');
const isTestHelper = rel => rel.split('/').includes('testing');

function sourceFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap(e => {
    const p = join(dir, e.name);
    return e.isDirectory() ? sourceFiles(p) : isSource(e.name) ? [p] : [];
  });
}

const imports = sourceFiles(appDir)
  .map(f => './' + relative(join(root, 'src'), f).split(sep).join('/').replace(/\.ts$/, ''))
  .filter(rel => !isTestHelper(rel))
  .sort();

writeFileSync(tempSpec, [
  '/* Generated by scripts/test-coverage.mjs and deleted after the run; do not edit or commit. */',
  ...imports.map(i => `import '${i}';`),
  '',
  `describe('coverage: every app source file', () => {`,
  `  it('loads all ${imports.length} files without throwing', () => expect(true).toBeTrue());`,
  '});',
  '',
].join('\n'));

let status = 1;
try {
  const args = ['ng', 'test', '--watch=false', '--browsers=ChromeHeadless', '--code-coverage', ...process.argv.slice(2)];
  status = spawnSync('npx', args, { cwd: root, stdio: 'inherit', shell: true }).status ?? 1;
} finally {
  rmSync(tempSpec, { force: true });
}
process.exit(status);
